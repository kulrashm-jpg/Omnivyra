      isContentLoading,
      contentAssets,
      handleTrackingLinkClick,
      handleRegenerateContent,
      handleApproveContent,
      handleRejectContent,
      handleGenerateContent,
      performanceWeekNumber,
      setPerformanceWeekNumber,
      handleApplyInsightsToWeek,
      isPerformanceLoading,
      analyticsReport,
      learningInsights,
      campaignMemory,
      memoryOverlap,
      isBusinessLoading,
      forecastReport,
