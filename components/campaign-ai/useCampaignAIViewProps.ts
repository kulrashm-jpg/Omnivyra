      aiHistory,
      isHistoryLoading,
      isAuditLoading,
      auditReport,
      isHealthLoading,
      healthReport,
      optimizeWeekNumber,
      setOptimizeWeekNumber,
      optimizeReason,
      setOptimizeReason,
      handleOptimizeWeek,
